// Builds the prototype into ./docs (plain files: open docs/index.html, or let GitHub Pages serve /docs).
// Also self-hosts the fonts, copies the PWA files from ./public and writes the service worker.
// Usage: node build.mjs        (or: npm run build)
import { build } from "esbuild";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

mkdirSync("docs/assets/fonts", { recursive: true });
// Copy by rewriting in place (works even where files cannot be deleted and re-created)
const copy = (from, to) => { mkdirSync(join(to, ".."), { recursive: true }); writeFileSync(to, readFileSync(from)); };
function copyDir(from, to, skip = () => false) {
  for (const name of readdirSync(from)) {
    const a = join(from, name), b = join(to, name);
    if (skip(a)) continue;
    statSync(a).isDirectory() ? copyDir(a, b, skip) : copy(a, b);
  }
}
await build({
  entryPoints: ["src/main.jsx"],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2020", "safari15"],
  jsx: "automatic",
  loader: { ".js": "jsx" },
  outfile: "docs/assets/app.js",
  define: { "process.env.NODE_ENV": '"production"' },
  nodePaths: process.env.NODE_PATH ? process.env.NODE_PATH.split(":") : [],
  logLevel: "info",
});
copy("index.html", "docs/index.html");
writeFileSync("docs/.nojekyll", "");

// Fonts: copied from @fontsource so the app opens offline and without Google Fonts
const faces = [
  ["Inter", "inter", [400, 500, 600, 700]],
  ["Plus Jakarta Sans", "plus-jakarta-sans", [600, 700, 800]],
  ["Roboto Mono", "roboto-mono", [400, 700]],
];
let fontCss = "/* Generated by build.mjs from @fontsource (latin). */\n";
for (const [family, pkg, weights] of faces) {
  for (const w of weights) {
    const file = `${pkg}-latin-${w}-normal.woff2`;
    copy(`node_modules/@fontsource/${pkg}/files/${file}`, `docs/assets/fonts/${file}`);
    fontCss += `@font-face { font-family: "${family}"; font-style: normal; font-weight: ${w}; font-display: swap; src: url("fonts/${file}") format("woff2"); }\n`;
  }
}
writeFileSync("docs/assets/fonts.css", fontCss);

// PWA files: manifest and icons
if (existsSync("public")) copyDir("public", "docs", (src) => src.endsWith("sw.template.js") || src.endsWith(".svg"));

// Service worker: precache every built file, versioned by content hash
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (!/sw\.js$|\.nojekyll$|\.DS_Store$/.test(name)) files.push(relative("docs", p).split("\\").join("/"));
  }
})("docs");
files.sort();
const hash = createHash("sha1");
for (const f of files) hash.update(f).update(readFileSync(join("docs", f)));
const precache = ["./", ...files.map((f) => "./" + f)];
writeFileSync("docs/sw.js", readFileSync("public/sw.template.js", "utf8")
  .replace("__VERSION__", hash.digest("hex").slice(0, 10))
  .replace("__PRECACHE__", JSON.stringify(precache, null, 2)));
console.log(`PWA: ${precache.length} files precached`);
